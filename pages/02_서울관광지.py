# 관광지 이름 리스트 추출
attraction_names = [place["name"] for place in seoul_attractions]

# 셀렉트박스 생성
selected_name = st.selectbox("자세히 보고 싶은 서울의 관광지를 선택하세요:", attraction_names)

# 선택된 관광지의 데이터 매칭
selected_place = next(place for place in seoul_attractions if place["name"] == selected_name)

# 선택된 관광지 상세 화면 UI 구성
st.markdown(f"### 📍 {selected_place['name']}")
inner_col1, inner_col2 = st.columns([1, 3])
with inner_col1:
    st.metric(label="🚇 가장 가까운 지하철역", value=selected_place["subway"])
with inner_col2:
    st.success(f"**✨ 추천 놀거리 및 액티비티**\n\n{selected_place['activity']}")

st.write("---")

